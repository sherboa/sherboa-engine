@pytest.mark.parametrize(
    "filename",
    [
        "thumbnail_0001.png",
        "thumbnail_1.jpg",
        "secret.txt",
        "..",
        "thumbnail_0001.jpg.bak",
    ],
)
def test_invalid_filename_returns_404(client, tmp_path, filename):
    analysis_id = str(uuid.uuid4())
    create_thumbnail(tmp_path, analysis_id)

    response = client.get(
        f"/thumbnails/{analysis_id}/reference/{filename}"
    )

    assert response.status_code == 404


def test_missing_thumbnail_returns_404(client, tmp_path):
    analysis_id = str(uuid.uuid4())
    (tmp_path / analysis_id / "reference").mkdir(parents=True)

    response = client.get(
        f"/thumbnails/{analysis_id}/reference/thumbnail_0001.jpg"
    )

    assert response.status_code == 404


def test_thumbnail_is_not_served_while_generation_is_in_progress(
    client, tmp_path
):
    analysis_id = str(uuid.uuid4())
    create_thumbnail(tmp_path, analysis_id)

    marker = tmp_path / analysis_id / ".generating"
    marker.touch()

    response = client.get(
        f"/thumbnails/{analysis_id}/reference/thumbnail_0001.jpg"
    )

    assert response.status_code == 404


def test_symlink_cannot_escape_video_directory(client, tmp_path):
    analysis_id = str(uuid.uuid4())
    image_path = create_thumbnail(tmp_path, analysis_id)

    outside_file = tmp_path / "outside.jpg"
    outside_file.write_bytes(b"outside content")

    # Replace the expected thumbnail with a symlink to an outside file
    image_path.unlink()

    try:
        image_path.symlink_to(outside_file)
    except (OSError, NotImplementedError):
        pytest.skip("symlink creation is not supported in this environment")

    response = client.get(
        f"/thumbnails/{analysis_id}/reference/thumbnail_0001.jpg"
    )

    assert response.status_code == 404


def test_expired_thumbnail_is_deleted_and_returns_404(client, tmp_path):
    """
    Expired analysis thumbnails must be deleted and cannot be served.
    """
    analysis_id = str(uuid.uuid4())
    image_path = create_thumbnail(tmp_path, analysis_id)
    analysis_dir = tmp_path / analysis_id

    expired_time = (
        time.time() - thumbnails.THUMBNAIL_RETENTION_SECONDS - 10
    )
    os.utime(analysis_dir, (expired_time, expired_time))

    response = client.get(
        f"/thumbnails/{analysis_id}/reference/thumbnail_0001.jpg"
    )

    assert response.status_code == 404
    assert not analysis_dir.exists()
